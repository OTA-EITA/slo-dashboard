import { useId, useState } from "react";
import { thresholds } from "../burn";

/** Shows the burn-rate alert thresholds slo-report would generate for an SLO. */
export function ThresholdCalculator() {
  const [objective, setObjective] = useState("99.9");
  const [window, setWindow] = useState("30d");
  const objectiveId = useId();
  const windowId = useId();

  let rows: ReturnType<typeof thresholds> = [];
  let error = "";
  try {
    rows = thresholds(Number(objective), window);
  } catch (e) {
    error = (e as Error).message;
  }

  return (
    <section className="card" aria-labelledby="calc-title">
      <h2 id="calc-title">Burn-rate alert thresholds</h2>
      <p className="muted">
        Multi-window, multi-burn-rate alerts from the Google SRE Workbook, as generated by{" "}
        <code>slo-report generate</code>.
      </p>
      <div className="inputs">
        <label htmlFor={objectiveId}>Objective (%)</label>
        <input
          id={objectiveId}
          inputMode="decimal"
          value={objective}
          onChange={(e) => {
            setObjective(e.target.value);
          }}
        />
        <label htmlFor={windowId}>Window</label>
        <input
          id={windowId}
          value={window}
          onChange={(e) => {
            setWindow(e.target.value);
          }}
        />
      </div>
      {error ? (
        <p role="alert" className="bad-text">
          {error}
        </p>
      ) : (
        <table>
          <thead>
            <tr>
              <th scope="col">Severity</th>
              <th scope="col">Windows</th>
              <th scope="col">Budget spent</th>
              <th scope="col">Burn rate</th>
              <th scope="col">Error ratio</th>
            </tr>
          </thead>
          <tbody>
            {rows.map((r) => (
              <tr key={r.longLabel}>
                <td>{r.severity}</td>
                <td>
                  {r.longLabel} &amp; {r.shortLabel}
                </td>
                <td>{(r.consumption * 100).toFixed(0)}%</td>
                <td>{r.factor}x</td>
                <td>&gt; {r.errorRatio}</td>
              </tr>
            ))}
          </tbody>
        </table>
      )}
    </section>
  );
}
